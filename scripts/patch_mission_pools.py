def replace_block(text, start_marker, new_block):
    i = text.find(start_marker)
    if i < 0:
        raise SystemExit(f'marker not found: {start_marker!r}')
    j = text.find('];', i)
    if j < 0:
        raise SystemExit('block end not found')
    j += len('];')
    return text[:i] + new_block + text[j:]

