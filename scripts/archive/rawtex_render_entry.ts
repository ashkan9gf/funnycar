import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { MeshoptDecoder } from 'three/examples/jsm/libs/meshopt_decoder.module.js';

const car = new URLSearchParams(location.search).get('car') || 'pride_raw_tex';
const buf = await fetch(`/assets/models/vehicles/${car}.glb`).then((r) => r.arrayBuffer());
const loader = new GLTFLoader();
loader.setMeshoptDecoder(MeshoptDecoder);
const gltf = await new Promise((res, rej) => loader.parse(buf, '', res, rej));
const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setSize(560, 420);
renderer.setClearColor(0xdfe8ee);
renderer.outputColorSpace = THREE.SRGBColorSpace;
document.body.style.margin = '0';
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
scene.add(new THREE.AmbientLight(0xffffff, 1.2));
const dl = new THREE.DirectionalLight(0xffffff, 1.5);
dl.position.set(3, 6, 4);
scene.add(dl);
scene.add(gltf.scene);
gltf.scene.updateMatrixWorld(true);
const bb = new THREE.Box3().setFromObject(gltf.scene);
const c = bb.getCenter(new THREE.Vector3());
const size = bb.getSize(new THREE.Vector3());
const cam = new THREE.PerspectiveCamera(38, 560 / 420, 0.1, 4000);
cam.position.set(c.x + size.x * 1.1, c.y + size.y * 0.8, c.z + size.z * 1.3);
cam.lookAt(c);
renderer.render(scene, cam);
const img = renderer.domElement.toDataURL('image/png');
const im = new Image();
im.src = img;
document.body.appendChild(im);
(window as unknown as { __DONE: number }).__DONE = 1;
