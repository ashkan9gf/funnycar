/**
 * dialogues.ts — جملات طنز بازی (Data-Driven)
 * ============================================================
 * ⭐ هیچ جمله طنزی نباید داخل منطق بازی نوشته شود!
 * همه متن‌ها اینجا تعریف می‌شوند و VoiceManager فقط با «کلید رویداد» کار می‌کند.
 *
 * قواعد نوشتن (طبق GAME_DESIGN_FA.md بخش ۸):
 *  - کوتاه: حداکثر ~40 کاراکتر (حباب گفتار)
 *  - محترمانه: بدون توهین به قومیت/مذهب/جنسیت/شغل
 *  - آشنا: از کوچه و بازار، نه جوک کلیشه‌ای
 *  - متنوع: حداقل 4 خط برای هر رویداد
 *
 * ساختار هر رویداد:
 *  - lines:     Pool جمله‌ها (انتخاب تصادفی با جلوگیری از تکرار پشت سر هم)
 *  - speaker:   چه کسی می‌گوید (برای پرتره حباب)
 *  - priority:  اولویت صوتی 0-5 (بخش Voice سند مادر)
 *  - cooldownMs: حداقل فاصله بین دو پخش همین رویداد (جلوگیری از آزاردهندگی)
 *  - chance:    احتمال پخش هنگام تریگر شدن رویداد (0 تا 1)
 */

